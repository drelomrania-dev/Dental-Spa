import {test,expect} from '@playwright/test'

test('dashboard CRM and ledger reports show empty states and audited demo downloads',async({page})=>{
  test.skip(Boolean(process.env.E2E_BASE_URL||process.env.E2E_SUPABASE_URL),'Synthetic local-data check only')
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Conversion CRM'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Encaissements opérationnels'})).toBeVisible()
  await expect(page.getByText('Registre financier, distinct du chiffre d’affaires comptable.')).toBeVisible()
  await page.goto('/reports')
  await expect(page.getByText('Rapprochement du registre : brut − corrections = net.')).toBeVisible()
  const reportDownload=page.waitForEvent('download')
  await page.getByRole('button',{name:'Exporter CSV'}).click()
  expect((await reportDownload).suggestedFilename()).toMatch(/^encaissements-/)
  await page.goto('/payment-history')
  const historyDownload=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export CSV'}).click()
  expect((await historyDownload).suggestedFilename()).toBe('historique-paiements.csv')
  const receiptDownload=page.waitForEvent('download')
  await page.getByRole('button',{name:'PDF'}).first().click()
  expect((await receiptDownload).suggestedFilename()).toMatch(/\.pdf$/)
  await page.goto('/settings')
  await expect(page.getByText('finance.payment_history.exported')).toBeVisible()
  await expect(page.getByText('finance.report.exported')).toBeVisible()
  await expect(page.getByText('finance.receipt.exported')).toBeVisible()
})
