import { test, expect } from '@playwright/test'

test('shows dated payment choices, receipt document and cash reconciliation', async ({page}) => {
  test.skip(Boolean(process.env.E2E_BASE_URL || process.env.E2E_SUPABASE_URL),'Synthetic local-data check only')
  await page.goto('/payments')
  await page.getByLabel('Patient').selectOption('p2')
  await page.getByLabel('Soin').selectOption('t7')
  await page.getByRole('button',{name:'Mensuel'}).click()
  await expect(page.getByLabel('Première échéance')).toBeVisible()
  await page.getByLabel('Nombre de mensualités').fill('4')
  await expect(page.getByText('Reste à payer')).toBeVisible()
  await page.getByRole('button',{name:'3 fois'}).click()
  await expect(page.getByLabel('Nombre de mensualités')).toHaveCount(0)
  await page.getByLabel('Moyen').selectOption('Carte')
  await page.getByRole('button',{name:'Valider le paiement'}).click()
  await expect(page.getByText('Paiement enregistré',{exact:false}).last()).toBeVisible()
  await expect(page.getByRole('button',{name:'Imprimer le ticket 80 mm'})).toBeVisible()
  await expect(page.locator('#receipt-print').getByText('Numéro')).toBeVisible()

  await page.goto('/collection-sessions')
  await page.getByRole('button',{name:'Ouvrir ma session'}).click()
  await page.getByLabel('Fonds de caisse initial').fill('100')
  await page.getByRole('button',{name:'Ouvrir',exact:true}).click()
  await expect(page.getByText('Espèces attendues, fonds inclus')).toBeVisible()
  await page.getByLabel('Espèces comptées').fill('100')
  await page.getByRole('button',{name:'Soumettre'}).click()
  await expect(page.getByText('Submitted')).toBeVisible()
  await page.getByRole('button',{name:'Valider'}).click()
  await expect(page.getByText('Validated')).toBeVisible()
})
