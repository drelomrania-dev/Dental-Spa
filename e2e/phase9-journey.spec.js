import { test, expect } from '@playwright/test'

test('synthetic lead through booking, clinical plan, approval, cash and reports', async ({ page }) => {
  test.skip(Boolean(process.env.E2E_BASE_URL || process.env.E2E_SUPABASE_URL), 'Synthetic demo journey only')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/acquisition')
  await page.getByRole('button', { name: 'Nouveau prospect' }).click()
  const leadDialog = page.getByRole('dialog', { name: 'Nouveau prospect' })
  await leadDialog.getByLabel('Prénom').fill('Parcours')
  await leadDialog.getByLabel('Nom', { exact: true }).fill('Neuf')
  await leadDialog.getByLabel('Téléphone').fill('0600999942')
  await leadDialog.getByLabel('Besoin / motif').fill('Contrôle synthétique')
  await leadDialog.getByRole('button', { name: 'Créer le prospect' }).click()
  await expect(page.getByRole('heading', { name: 'Parcours Neuf', level: 1 })).toBeVisible()
  const leadUrl = page.url()
  await page.getByRole('button', { name: 'Relance' }).click()
  await page.getByLabel('Échéance').fill('2026-11-15T10:00')
  await page.getByRole('button', { name: 'Planifier' }).click()
  await expect(page.getByText('Relancer le prospect')).toBeVisible()

  await page.goto('/book/consultation')
  await page.locator('.booking-service-list button').first().click()
  await page.getByLabel('Votre motif').fill('Contrôle synthétique réservé')
  await page.getByRole('button', { name: 'Continuer' }).click()
  await page.locator('.calendar-grid button:not([disabled])').first().click()
  await page.locator('.booking-time-step .time-list button').first().click()
  await page.getByLabel('Prénom').fill('Parcours')
  await page.getByLabel('Nom', { exact: true }).fill('Neuf')
  await page.getByRole('button', { name: 'Continuer' }).click()
  await page.getByLabel('Téléphone').fill('0600999942')
  await page.getByRole('button', { name: 'Continuer' }).click()
  await page.getByRole('button', { name: 'Confirmer le rendez-vous' }).click()
  await expect(page.getByRole('heading', { name: 'Votre rendez-vous est enregistré' })).toBeVisible()
  const booked = await page.evaluate(() => {
    const patient = JSON.parse(localStorage.getItem('dentalflow:patients')).find(row => row.firstName === 'Parcours' && row.lastName === 'Neuf')
    const appointment = JSON.parse(localStorage.getItem('dentalflow:appointments')).find(row => row.patientId === patient.id)
    return { patientId: patient.id, appointmentId: appointment.id }
  })
  await page.goto(leadUrl)
  await expect(page.getByLabel('Étape')).toHaveValue('Rendez-vous')
  await page.getByRole('button', { name: 'Convertir en patient' }).click()
  await expect(page.getByRole('link', { name: 'Ouvrir le patient' })).toBeVisible()
  await page.goto('/appointments')
  await expect(page.getByText('Parcours Neuf')).toBeVisible()
  await page.goto(`/patients/${booked.patientId}`)
  await expect(page.getByText('Contrôle synthétique réservé')).toBeVisible()

  await page.goto('/clinical')
  await page.getByRole('button', { name: 'Ouvrir une consultation' }).click()
  await page.getByLabel('Rendez-vous lié').selectOption(booked.appointmentId)
  await page.getByLabel('Notes cliniques').fill('Note synthétique privée du parcours')
  await page.getByRole('button', { name: 'Enregistrer la consultation' }).click()
  await expect(page.getByText('Rendez-vous lié · Note synthétique privée du parcours')).toBeVisible()
  await page.goto(`/patients/${booked.patientId}`)
  await expect(page.getByText('Note synthétique privée du parcours')).toBeVisible()

  await page.evaluate(() => localStorage.setItem('dentalflow:currentUser', 'u2'))
  await page.goto('/approvals')
  await page.getByRole('button', { name: 'Demander une remise' }).click()
  await page.getByLabel('Patient').selectOption(booked.patientId)
  await page.getByLabel('Soin').selectOption('t1')
  await page.getByLabel('Prix proposé (MAD)').fill('300')
  await page.getByLabel('Justification').fill('Accord synthétique du parcours')
  await page.getByRole('button', { name: 'Soumettre la demande' }).click()
  await expect(page.getByText('Accord synthétique du parcours')).toBeVisible()
  await page.evaluate(() => localStorage.setItem('dentalflow:currentUser', 'u1'))
  await page.reload()
  await page.getByTitle('Approuver').click()
  await expect(page.getByText('Approved')).toBeVisible()

  await page.goto('/collection-sessions')
  await page.getByRole('button', { name: 'Ouvrir ma session' }).click()
  await page.getByLabel('Fonds de caisse initial').fill('100')
  await page.getByRole('button', { name: 'Ouvrir', exact: true }).click()
  await page.goto('/payments')
  await page.getByLabel('Patient').selectOption(booked.patientId)
  await page.getByLabel('Soin').selectOption('t1')
  await expect(page.locator('.summary-cards strong').first()).toHaveText('300 DH')
  await page.getByRole('button', { name: '2 fois' }).click()
  await page.getByLabel('Montant reçu (MAD)').fill('50')
  await page.getByLabel('Moyen').selectOption('Espèces')
  await page.getByRole('button', { name: 'Valider le paiement' }).click()
  await expect(page.getByText('Paiement enregistré', { exact: false }).last()).toBeVisible()
  await page.goto('/collection-sessions')
  await expect(page.getByText('Espèces attendues, fonds inclus')).toBeVisible()
  await page.getByLabel('Espèces comptées').fill('150')
  await page.getByRole('button', { name: 'Soumettre' }).click()
  await expect(page.getByText('Submitted')).toBeVisible()
  await page.getByRole('button', { name: 'Valider' }).click()
  await expect(page.getByText('Validated')).toBeVisible()
  await page.goto('/reports')
  await expect(page.getByText('Rapprochement du registre : brut − corrections = net.')).toBeVisible()
  await expect(page.getByText('50 DH', { exact: true }).first()).toBeVisible()
  await page.goto('/reminders')
  await expect(page.getByRole('heading', { name: 'Rappels', exact: true })).toBeVisible()
  await page.getByLabel('Patient').selectOption(booked.patientId)
  await page.getByLabel('Preuve ou motif').fill('Consentement synthétique du parcours')
  await page.getByRole('button', { name: 'Enregistrer la préférence' }).click()
  await page.getByRole('button', { name: 'Préparer les rappels dus' }).click()
  await expect(page.locator('tbody')).not.toContainText('Note synthétique privée du parcours')
})
