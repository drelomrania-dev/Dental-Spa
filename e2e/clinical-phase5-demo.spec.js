import { test, expect } from '@playwright/test'

test('links a visit to an appointment and carries an approved price into the plan', async ({ page }) => {
  test.skip(Boolean(process.env.E2E_BASE_URL || process.env.E2E_SUPABASE_URL), 'The synthetic demo check runs only in local-data mode')
  await page.goto('/clinical')
  await page.getByRole('button',{name:'Ouvrir une consultation'}).click()
  await page.getByLabel('Rendez-vous lié').selectOption('a1')
  await page.getByLabel('Service effectué').selectOption('t3')
  await page.getByLabel('Notes cliniques').fill('Clinical phase 5 synthetic note')
  await page.getByLabel('Instructions de suivi').fill('Review next week')
  await page.getByRole('button',{name:'Enregistrer la consultation'}).click()
  await expect(page.getByText('Rendez-vous lié · Clinical phase 5 synthetic note')).toBeVisible()
  await page.getByRole('button',{name:'Modifier'}).first().click()
  await page.getByLabel('Notes cliniques').fill('Clinical phase 5 updated note')
  await page.getByRole('button',{name:'Enregistrer la consultation'}).click()
  await expect(page.getByText('Rendez-vous lié · Clinical phase 5 updated note')).toBeVisible()
  await page.goto('/patients/p1')
  await expect(page.getByText('Clinical phase 5 updated note')).toBeVisible()

  await page.evaluate(() => localStorage.setItem('dentalflow:currentUser','u2'))
  await page.goto('/approvals')
  await page.getByRole('button',{name:'Demander une remise'}).click()
  await page.getByLabel('Patient').selectOption('p1')
  await page.getByLabel('Soin').selectOption('t3')
  await page.getByLabel('Prix proposé (MAD)').fill('500')
  await page.getByLabel('Justification').fill('Synthetic phase 5 discount')
  await page.getByRole('button',{name:'Soumettre la demande'}).click()
  await expect(page.getByText('Synthetic phase 5 discount')).toBeVisible()

  await page.evaluate(() => localStorage.setItem('dentalflow:currentUser','u1'))
  await page.reload()
  await page.getByTitle('Rejeter').click()
  await expect(page.getByText('Prix non validé')).toBeVisible()
  await page.goto('/clinical')
  await expect(page.getByText('600 DH · 1 étape(s)')).toBeVisible()

  await page.evaluate(() => localStorage.setItem('dentalflow:currentUser','u2'))
  await page.goto('/approvals')
  await page.getByRole('button',{name:'Demander une remise'}).click()
  await page.getByLabel('Patient').selectOption('p1')
  await page.getByLabel('Soin').selectOption('t3')
  await page.getByLabel('Prix proposé (MAD)').fill('500')
  await page.getByLabel('Justification').fill('Second synthetic phase 5 request')
  await page.getByRole('button',{name:'Soumettre la demande'}).click()
  await page.evaluate(() => localStorage.setItem('dentalflow:currentUser','u1'))
  await page.reload()
  await page.getByTitle('Approuver').click()
  await expect(page.getByText('Décidé le', { exact:false }).first()).toBeVisible()
  await page.goto('/clinical')
  await expect(page.getByText('500 DH · 1 étape(s)')).toBeVisible()
})
