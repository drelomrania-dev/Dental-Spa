import { test, expect } from '@playwright/test'

test('tracks a lost lead through recovery, quote, follow-up and revoked intake link in demo mode', async ({ page }) => {
  test.skip(Boolean(process.env.E2E_SUPABASE_URL || process.env.E2E_BASE_URL),'This synthetic browser journey uses the local demo store.')
  await page.goto('/acquisition')
  await page.evaluate(() => {
    const key='dentalflow:clinic'
    const clinic=JSON.parse(localStorage.getItem(key)||'null')||{name:'Dental Spa',address:'Casablanca',timezone:'Africa/Casablanca'}
    localStorage.setItem(key,JSON.stringify({...clinic,currency:'EUR'}))
  })
  await page.reload()
  await page.getByRole('button',{name:'Nouveau prospect'}).click()
  await page.getByLabel('Prénom').fill('Mina')
  await page.getByLabel('Nom',{exact:true}).fill('Test')
  await page.getByLabel('Téléphone').fill('0600112233')
  await page.getByRole('dialog',{name:'Nouveau prospect'}).getByLabel('Source').selectOption('Instagram')
  await page.getByRole('button',{name:'Créer le prospect'}).click()
  await expect(page).toHaveURL(/\/acquisition\/[^/]+$/)
  const profileStage=page.locator('.lead-profile-controls').getByLabel('Étape')
  await profileStage.selectOption('Perdu')
  await expect(page.getByText('Nouveau → Perdu')).toBeVisible()
  await page.goto('/acquisition')
  await expect(page.locator('.lead-column').filter({has:page.getByText('Perdu',{exact:true})}).getByText('Mina Test')).toBeVisible()
  await page.getByRole('link',{name:/Mina Test/}).first().click()
  await expect(profileStage).toHaveValue('Perdu')
  await profileStage.selectOption('Contacte')
  await expect(page.getByText('Perdu → Contacte')).toBeVisible()

  await page.getByRole('button',{name:'Relance'}).click()
  await page.getByLabel('Échéance').fill('2026-11-01T10:00')
  await page.getByRole('button',{name:'Planifier'}).click()
  await expect(page.getByText('Relancer le prospect')).toBeVisible()

  await page.getByRole('button',{name:'Devis',exact:true}).click()
  await page.getByLabel('Montant (EUR)').fill('1200')
  await page.getByRole('button',{name:'Créer le devis'}).click()
  await expect(page.getByText('1 200 EUR')).toBeVisible()
  await page.getByLabel('Statut du devis Proposition de soins').selectOption('Envoye')
  await page.getByLabel('Statut du devis Proposition de soins').selectOption('Accepte')
  await expect(page.getByText('Brouillon → Envoye → Accepte')).toBeVisible()

  await page.getByRole('button',{name:'Inviter'}).click()
  await page.getByRole('button',{name:'Copier un lien'}).click()
  const intakeUrl=await page.locator('.invite-result input').inputValue()
  await page.reload()
  await page.getByRole('button',{name:'Révoquer'}).click()
  await page.goto(intakeUrl)
  await expect(page.getByRole('heading',{name:'Lien indisponible'})).toBeVisible()

  await page.goto('/acquisition')
  await page.getByRole('button',{name:'Nouveau prospect'}).click()
  await page.getByRole('dialog',{name:'Nouveau prospect'}).getByLabel('Prénom').fill('Autre')
  await page.getByRole('dialog',{name:'Nouveau prospect'}).getByLabel('Téléphone').fill('06 00 11 22 33')
  await page.getByRole('button',{name:'Créer le prospect'}).click()
  await expect(page.getByText('Un prospect avec ce contact existe déjà. Son dossier a été ouvert.')).toBeVisible()
  await expect(page.getByRole('heading',{name:'Mina Test',level:1})).toBeVisible()
})

test('requires contact consent and completes a public intake once in demo mode', async ({ page }) => {
  test.skip(Boolean(process.env.E2E_SUPABASE_URL || process.env.E2E_BASE_URL),'This synthetic browser journey uses the local demo store.')
  await page.goto('/acquisition')
  await page.getByRole('button',{name:'Nouveau prospect'}).click()
  await page.getByRole('dialog',{name:'Nouveau prospect'}).getByLabel('Prénom').fill('Nadia')
  await page.getByRole('dialog',{name:'Nouveau prospect'}).getByLabel('Téléphone').fill('0611223344')
  await page.getByRole('button',{name:'Créer le prospect'}).click()
  const leadUrl=page.url()
  await page.getByRole('button',{name:'Inviter'}).click()
  await page.getByRole('button',{name:'Copier un lien'}).click()
  const intakeUrl=await page.locator('.invite-result input').inputValue()
  await page.goto(intakeUrl)
  await expect(page.getByRole('heading',{name:'Vos coordonnées'})).toBeVisible()
  await page.getByLabel('Téléphone').fill('0611223344')
  await page.getByRole('button',{name:'Continuer'}).click()
  await page.getByLabel('Que souhaitez-vous améliorer ou faire contrôler ?').fill('Contrôle dentaire')
  await page.getByRole('button',{name:'Continuer'}).click()
  await page.getByRole('button',{name:'Continuer'}).click()
  await expect(page.getByRole('button',{name:'Envoyer au cabinet'})).toBeDisabled()
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'Envoyer au cabinet'}).click()
  await expect(page.getByText('Formulaire reçu')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Formulaire reçu')).toBeVisible()
  await page.goto(leadUrl)
  await expect(page.getByLabel('Étape')).toHaveValue('Qualifie')
})

test('keeps the public intake usable on a narrow phone screen in demo mode', async ({ page }) => {
  test.skip(Boolean(process.env.E2E_SUPABASE_URL || process.env.E2E_BASE_URL),'This synthetic browser journey uses the local demo store.')
  await page.setViewportSize({width:390,height:844})
  await page.goto('/acquisition')
  await page.getByRole('button',{name:'Nouveau prospect'}).click()
  await page.getByRole('dialog',{name:'Nouveau prospect'}).getByLabel('Prénom').fill('Samira')
  await page.getByRole('dialog',{name:'Nouveau prospect'}).getByLabel('Téléphone').fill('0611334455')
  await page.getByRole('button',{name:'Créer le prospect'}).click()
  await page.getByRole('button',{name:'Inviter'}).click()
  await page.getByRole('button',{name:'Copier un lien'}).click()
  const intakeUrl=await page.locator('.invite-result input').inputValue()
  await page.goto(intakeUrl)
  for(const heading of ['Vos coordonnées','Votre besoin','Photos guidées','Consentement']){
    await expect(page.getByRole('heading',{name:heading})).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(391)
    if(heading==='Vos coordonnées')await page.getByLabel('Téléphone').fill('0611334455')
    if(heading==='Votre besoin')await page.getByLabel('Que souhaitez-vous améliorer ou faire contrôler ?').fill('Contrôle du sourire')
    if(heading!=='Consentement')await page.getByRole('button',{name:'Continuer'}).click()
  }
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'Envoyer au cabinet'}).click()
  await expect(page.getByText('Formulaire reçu')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(391)
})
