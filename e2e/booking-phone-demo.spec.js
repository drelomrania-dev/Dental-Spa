import { test, expect } from '@playwright/test'

test('books on a phone and keeps the reserved chair out of later slot choices', async ({ page }) => {
  test.skip(Boolean(process.env.E2E_BASE_URL || process.env.E2E_SUPABASE_URL), 'The demo booking check runs only in local-data mode')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/book/consultation')
  await expect(page.getByRole('heading', { name: 'Quel soin souhaitez-vous ?' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await expect(page.locator('.booking-event-panel .booking-share-box')).toBeHidden()
  await page.locator('.booking-service-list button').first().click()
  await page.getByLabel('Votre motif').fill('Contrôle synthétique de réservation mobile')
  await page.getByRole('button', { name: 'Continuer' }).click()
  const dateButton = page.locator('.calendar-grid button:not([disabled])').first()
  const dateLabel = await dateButton.getAttribute('aria-label')
  await dateButton.click()
  const slot = page.locator('.booking-time-step .time-list button').first()
  await expect(slot).toBeVisible()
  const bookedTime = (await slot.textContent()).trim()
  await slot.click()
  await page.getByLabel('Prénom').fill('Phase')
  await page.getByLabel('Nom', { exact: true }).fill('Quatre')
  await page.getByRole('button', { name: 'Continuer' }).click()
  await page.getByLabel('Téléphone').fill('+212 6 00 00 04 01')
  await page.getByRole('button', { name: 'Continuer' }).click()
  await expect(page.getByText('Contrôle synthétique de réservation mobile')).toBeVisible()
  await page.getByRole('button', { name: 'Confirmer le rendez-vous' }).click()
  await expect(page.getByRole('heading', { name: 'Votre rendez-vous est enregistré' })).toBeVisible()
  await expect(page.locator('.booking-reference strong')).toContainText('RDV-')
  await page.goto('/appointments')
  await expect(page.getByText('Phase Quatre')).toBeVisible()
  await expect(page.locator('.booking-card').filter({ hasText: 'Phase Quatre' }).getByRole('link', { name: 'Phase Quatre' })).toHaveAttribute('href', /\/patients\//)
  await page.goto('/book/consultation')
  await page.locator('.booking-service-list button').first().click()
  await page.getByLabel('Votre motif').fill('Nouvelle demande synthétique')
  await page.getByRole('button', { name: 'Continuer' }).click()
  await page.getByRole('button', { name: dateLabel }).click()
  await expect(page.locator('.booking-time-step .time-list')).toBeVisible()
  await expect(page.locator('.booking-time-step .time-list button').filter({ hasText: bookedTime })).toHaveCount(0)
})
